CREATE TABLE IF NOT EXISTS devis (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference     VARCHAR(30) UNIQUE,
    client_id     BIGINT      NOT NULL,
    date_creation TIMESTAMP   NOT NULL
);

CREATE TABLE IF NOT EXISTS version_devis (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devis_id       BIGINT      NOT NULL REFERENCES devis (id),
    numero_version INTEGER     NOT NULL,
    statut         VARCHAR(20) NOT NULL,
    date_emission  DATE,
    date_validite  DATE,
    commentaire    VARCHAR(2000),
    total_ht       DECIMAL(12,2),
    total_tva      DECIMAL(12,2),
    total_ttc      DECIMAL(12,2),
    CONSTRAINT uk_version_devis UNIQUE (devis_id, numero_version)
);

CREATE TABLE IF NOT EXISTS ligne_devis (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id       BIGINT        NOT NULL REFERENCES version_devis (id),
    produit_id       BIGINT        NOT NULL,
    name             VARCHAR(255)  NOT NULL,
    quantite         INTEGER       NOT NULL,
    prix_unitaire_ht DECIMAL(10,2) NOT NULL,
    taux_tva         DECIMAL(5,2)  NOT NULL
);
