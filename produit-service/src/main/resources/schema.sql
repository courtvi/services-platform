CREATE TABLE IF NOT EXISTS produit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)  NOT NULL,
    description VARCHAR(1000),
    price       DECIMAL(10,2) NOT NULL,
    taux_tva    DECIMAL(5,2)  NOT NULL
);

-- Fiche d'un produit dans une boutique (composition : le prix reste dans produit).
CREATE TABLE IF NOT EXISTS fiche_boutique (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id  BIGINT       NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    boutique_id VARCHAR(50)  NOT NULL,
    origine     VARCHAR(100),
    unite       VARCHAR(50),
    categorie   VARCHAR(50),
    tag_cle     VARCHAR(50),
    image       VARCHAR(255),
    rupture     BOOLEAN      NOT NULL DEFAULT FALSE,
    annee       VARCHAR(10),
    actif       BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_fiche_boutique UNIQUE (boutique_id, produit_id)
);
