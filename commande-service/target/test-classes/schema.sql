DROP TABLE IF EXISTS LIGNECOMMANDES;
DROP TABLE IF EXISTS COMMANDES;

CREATE TABLE COMMANDES (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID       VARCHAR(255) NOT NULL,
    REFERENCE     VARCHAR(100) NOT NULL,
    STATUT        VARCHAR(50)  NOT NULL DEFAULT 'CREEE',
    DATE_COMMANDE TIMESTAMP    NOT NULL,
    DATE_LIVRAISON TIMESTAMP    NOT NULL
);

CREATE TABLE LIGNECOMMANDES (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMMANDE_ID BIGINT       NOT NULL,
    ARTICLE     VARCHAR(255) NOT NULL,
    QUANTITE    INTEGER      NOT NULL,
    PRIX_UNITAIRE         DECIMAL(10,2)         NOT NULL,
    TOTAL       DECIMAL(10,2)         NOT NULL

);

CREATE TABLE IF NOT EXISTS CLIENT_REF (
   KEYCLOAK_ID VARCHAR(255) PRIMARY KEY,
   NUMERO_CLIENT VARCHAR(50) NOT NULL
);